import { test, expect } from '@playwright/test'

test('desktop dashboard and all five navigation entries', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '你好，欢迎来到字律' })).toBeVisible()
  await expect(page.locator('.stat-card')).toHaveCount(4)
  await expect(page.locator('.theme-card')).toHaveCount(3)
  await expect(page.getByText('还没有训练记录', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: /中文打字/ }).click()
  await expect(page).toHaveURL(/language=zh/)
  await page.goto('/')
  await page.getByRole('link', { name: /英文打字/ }).click()
  await expect(page).toHaveURL(/language=en/)
  for (const [path, title] of [['/', '首页'], ['/practice', '打字训练'], ['/library', '词库管理'], ['/history', '训练记录'], ['/settings', '设置']]) {
    const link = page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: new RegExp(title) })
    await link.click()
    await expect(link).toHaveAttribute('aria-current', 'page')
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(new URL(page.url()).hash || '#/').toBe(`#${path}`)
  }
})

for (const width of [320, 390, 768]) {
  test(`responsive menu and dashboard at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/')
    await expect(page.getByRole('navigation', { name: '主导航' })).not.toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: '打开菜单' }).click()
    await expect(page.getByRole('navigation', { name: '主导航' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: '打开菜单' })).toBeFocused()
    await page.getByRole('button', { name: '打开菜单' }).click()
    await page.getByRole('navigation').getByRole('link', { name: /设置/ }).click()
    await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible()
    await expect(page.getByRole('navigation')).not.toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}


test('theme language switching and compact dashboard links', async ({ page }) => {
  await page.goto('/')
  const themes = page.locator('.theme-card')
  await expect(themes).toHaveCount(3)
  await expect(themes.first()).toContainText('中国文学')
  await expect(page.getByRole('button', { name: '中文', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await themes.first().click()
  let query = new URLSearchParams(new URL(page.url()).hash.split('?')[1])
  expect(query.get('language')).toBe('zh')
  expect(query.get('theme')).toBe('中国文学')
  await page.goto('/')
  await page.getByRole('button', { name: 'English', exact: true }).click()
  await expect(themes).toHaveCount(3)
  await expect(themes.first()).toContainText('Daily Life')
  await expect(page.getByRole('button', { name: 'English', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await themes.first().click()
  query = new URLSearchParams(new URL(page.url()).hash.split('?')[1])
  expect(query.get('language')).toBe('en')
  expect(query.get('theme')).toBe('Daily Life')
  await page.goto('/')
  await page.getByRole('button', { name: 'English', exact: true }).click()
  await page.getByRole('button', { name: '中文', exact: true }).click()
  await expect(themes.first()).toContainText('中国文学')
  await page.getByRole('link', { name: '查看全部', exact: true }).click()
  await expect(page).toHaveURL(/#\/library$/)
  await page.goto('/')
  await page.getByRole('link', { name: '全部记录', exact: true }).click()
  await expect(page).toHaveURL(/#\/history$/)
})
