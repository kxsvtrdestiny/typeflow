import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
const base = new URL(process.argv[2] ?? 'http://127.0.0.1:3000/')
if (!base.pathname.endsWith('/')) base.pathname += '/'
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}) })
const failures = [], checks = []
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Shanghai' })
  page.on('pageerror', e => failures.push(e.message))
  page.on('console', msg => { if (msg.type() === 'error') failures.push(msg.text()) })
  page.on('response', r => { if (r.status() >= 400) failures.push(`${r.status()} ${r.url()}`) })
  for (const [route, title] of [['', '首页'], ['practice', '打字训练'], ['library', '词库管理'], ['history', '训练记录'], ['settings', '设置']]) {
    await page.goto(`${base}#/${route}`); await page.reload()
    await page.getByRole('heading', { name: title, exact: true }).waitFor()
  }
  checks.push('five hash routes and refresh')
  assert.equal(await page.title(), '字律 TypeRhythm')
  await page.getByRole('combobox', { name: '显示模式' }).selectOption('dark')
  await page.reload()
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark')
  assert.equal(await page.getByRole('spinbutton', { name: '每日训练目标（分钟）' }).inputValue(), '20')
  await page.goto(`${base}#/library`)
  await page.getByRole('button', { name: '新建主题', exact: true }).click()
  await page.getByRole('textbox', { name: '主题名称' }).fill('生产验证词库')
  await page.getByRole('button', { name: '保存主题', exact: true }).click()
  await page.locator('.library-card').filter({ hasText: '生产验证词库' }).getByRole('link', { name: '查看文章' }).click()
  await page.getByRole('button', { name: '导入文章', exact: true }).click()
  await page.getByLabel('选择 TXT / DOCX 文件').setInputFiles({ name: 'test.txt', mimeType: 'text/plain', buffer: Buffer.from('\uFEFF你好\r\nHello') })
  assert.equal(await page.getByRole('textbox', { name: '文章内容' }).inputValue(), '你好\nHello')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  assert.equal(await page.locator('.article-card').count(), 0)
  await page.getByRole('button', { name: '导入文章', exact: true }).click()
  await page.getByLabel('选择 TXT / DOCX 文件').setInputFiles(fileURLToPath(new URL('../tests/fixtures/plain-text.docx', import.meta.url)))
  const content = page.getByRole('textbox', { name: '文章内容' })
  await content.waitFor()
  const text = await content.inputValue()
  assert(text.includes('DOCX 中文练习') && text.includes('<script>not executable</script>'))
  await page.getByRole('button', { name: '保存文章', exact: true }).click()
  await page.getByRole('link', { name: '开始练习', exact: true }).click()
  await page.getByRole('button', { name: '开始训练', exact: true }).click()
  const input = page.getByRole('textbox', { name: '训练输入' })
  await input.pressSequentially('D', { delay: 20 })
  await input.fill(text)
  await page.getByText('成绩已保存到训练记录', { exact: true }).waitFor()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('typeflow.history')))
  assert.equal(saved.version, 2); assert.equal(saved.data.length, 1)
  assert.equal(saved.data[0].characterAnalysis.version, 1)
  await page.goto(`${base}#/history`); await page.reload()
  await page.locator('.recharts-wrapper').waitFor()
  assert.equal(await page.locator('.history-record').count(), 1)
  await page.getByText('错误字符分析', { exact: true }).click()
  await page.getByText('已比较次数：该标准字符已参与实际输入比较的次数。', { exact: true }).waitFor()
  checks.push('dark settings persistence, 20-minute default', 'TXT BOM/newlines/cancel', 'DOCX raw-text Worker import and training', 'v2 history, character aggregates and lazy chart')
  assert.deepEqual(failures, [])
  console.log(JSON.stringify({ base: String(base), passed: true, checks, browserErrors: failures }, null, 2))
} finally { await browser.close() }
