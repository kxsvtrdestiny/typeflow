import { test, expect } from '@playwright/test'
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    const now = new Date().toISOString()
    localStorage.setItem('typeflow.library', JSON.stringify({ version: 1, data: ['one', 'two'].map((id) => ({ id: `custom-${id}`, name: id === 'one' ? '导入目标' : '另一主题', language: 'zh', description: '', difficulty: 'beginner', isDefault: false, createdAt: now, updatedAt: now, articles: [] })) }))
  })
  await page.goto('/#/library/custom-one')
})
test('TXT preview edits title/theme/body, cancel writes nothing, saved text can train', async ({ page }) => {
  await page.getByRole('button', { name: '导入文章', exact: true }).click()
  await page.getByLabel('选择 TXT / DOCX 文件').setInputFiles({ name: '示例.txt', mimeType: 'text/plain', buffer: Buffer.from('\uFEFF你好\r\nHello.') })
  await expect(page.getByRole('textbox', { name: '文章内容' })).toHaveValue('你好\nHello.')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.article-card')).toHaveCount(0)
  await page.getByRole('button', { name: '导入文章', exact: true }).click()
  await page.getByLabel('选择 TXT / DOCX 文件').setInputFiles({ name: '示例.txt', mimeType: 'text/plain', buffer: Buffer.from('你好\nHello.') })
  await page.getByRole('textbox', { name: '文章标题' }).fill('修改标题')
  await page.getByRole('textbox', { name: '文章内容' }).fill('修改正文。')
  await page.getByRole('combobox', { name: '保存到主题' }).selectOption('custom-two')
  await page.getByRole('button', { name: '保存文章', exact: true }).click()
  await page.getByRole('link', { name: '返回词库', exact: true }).click()
  await page.locator('.library-card').filter({ hasText: '另一主题' }).getByRole('link', { name: '查看文章' }).click()
  await expect(page.locator('.article-card')).toContainText('修改标题')
  await page.getByRole('link', { name: '开始练习', exact: true }).click()
  await page.getByRole('button', { name: '开始训练', exact: true }).click()
  await page.getByRole('textbox', { name: '训练输入' }).pressSequentially('修改')
  await expect(page.getByTestId('training-counts')).toContainText('正确 2 · 错误 0')
})
test('DOCX is parsed locally as editable text without inserting HTML', async ({ page }) => {
  await page.getByRole('button', { name: '导入文章', exact: true }).click()
  await page.getByLabel('选择 TXT / DOCX 文件').setInputFiles('tests/fixtures/plain-text.docx')
  await expect(page.getByRole('textbox', { name: '文章内容' })).toHaveValue(/DOCX 中文练习/)
  await expect(page.getByRole('textbox', { name: '文章内容' })).toHaveValue(/<script>not executable<\/script>/)
  await page.getByRole('button', { name: '保存文章', exact: true }).click()
  await expect(page.locator('.article-card')).toContainText('DOCX 中文练习')
  await page.getByRole('link', { name: '开始练习', exact: true }).click()
  await page.getByRole('button', { name: '开始训练', exact: true }).click()
  await page.getByRole('textbox', { name: '训练输入' }).pressSequentially('DOCX')
  await expect(page.getByTestId('training-counts')).toContainText('正确 4 · 错误 0')
})
test('encoding retry, malformed DOCX and file size are reported without saving', async ({ page }) => {
  await page.getByRole('button', { name: '导入文章', exact: true }).click()
  await page.getByLabel('选择 TXT / DOCX 文件').setInputFiles({ name: 'gb.txt', mimeType: 'text/plain', buffer: Buffer.from([0xc4, 0xe3, 0xba, 0xc3]) })
  await expect(page.getByRole('alert')).toContainText('UTF-8')
  await page.getByRole('button', { name: '按 GB18030 重读' }).click()
  await expect(page.getByRole('textbox', { name: '文章内容' })).toHaveValue('你好')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '导入文章', exact: true }).click()
  await page.getByLabel('选择 TXT / DOCX 文件').setInputFiles({ name: 'bad.docx', mimeType: 'application/octet-stream', buffer: Buffer.from('not a docx') })
  await expect(page.getByRole('alert')).toContainText('DOCX')
  await page.getByLabel('选择 TXT / DOCX 文件').setInputFiles({ name: 'big.txt', mimeType: 'text/plain', buffer: Buffer.alloc(2 * 1024 * 1024 + 1, 'a') })
  await expect(page.getByRole('alert')).toContainText('2 MiB')
})
