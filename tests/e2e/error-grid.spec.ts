import { test, expect } from '@playwright/test'
test('all errors use compact two-column cards, preserve rankings/languages, and stack on mobile', async ({ page }) => {
  await page.addInitScript(() => {
    const date = new Date().toISOString()
    const data = ['en', 'zh'].map(language => {
      const targets = Array.from(language === 'en' ? 'AbCdEfGhIjKlMn' : '春夏秋冬山川湖海风雨星辰日月')
      const characters = targets.map((expected, index) => ({ expected, attempts: 10 + index, errors: index % 5 + 1 }))
      const submitted = characters.reduce((sum, c) => sum + c.attempts, 0)
      const errors = characters.reduce((sum, c) => sum + c.errors, 0)
      return { id: language, articleId: 'grid', articleTitle: '布局回归', themeId: 'grid-theme', themeName: '布局测试', language, mode: 'free', timedMinutes: 1, startedAt: date, completedAt: date, finishReason: 'article-completed', metrics: { cpm: 10, wpm: 2, accuracy: (submitted - errors) / submitted * 100, cumulativeAccuracy: (submitted - errors) / submitted * 100, correctCharacters: submitted - errors, incorrectCharacters: errors, submittedCharacters: submitted, totalInputCharacters: submitted, totalCorrectInputCharacters: submitted - errors, elapsedMs: 60000, progress: 1 }, characterAnalysis: { version: 1, characters } }
    })
    localStorage.setItem('typeflow.history', JSON.stringify({ version: 2, data }))
  })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/#/history')
  await page.getByText('错误字符分析', { exact: true }).click()
  const list = page.getByRole('list', { name: '易错字符' })
  const items = list.locator('li')
  await expect(items).toHaveCount(14)
  const boxes = () => items.evaluateAll(nodes => nodes.map(node => { const r = node.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height } }))
  const desktop = await boxes()
  expect(desktop[0].y).toBe(desktop[1].y)
  expect(desktop[0].x).toBeLessThan(desktop[1].x)
  expect(desktop[2].y).toBeGreaterThan(desktop[0].y)
  const detailGap = await items.first().evaluate(node => node.querySelector('.error-character-details')!.getBoundingClientRect().x - node.querySelector('strong')!.getBoundingClientRect().right)
  expect(detailGap).toBeLessThanOrEqual(12)
  await expect(items.first()).toContainText('次错误')
  await expect(items.first()).toContainText('次匹配')
  await expect(items.first()).toContainText('错误率')
  expect(await items.first().getAttribute('data-error-character')).toBe('山')
  await page.getByRole('combobox', { name: '错误分析排序' }).selectOption('highRate')
  expect(await items.first().getAttribute('data-error-character')).toBe('山')
  // In English the top frequency ties differ from the highest error rate.
  await page.getByRole('group', { name: '错误分析语言' }).getByRole('button', { name: 'English' }).click()
  await expect(items).toHaveCount(14)
  expect(await items.first().getAttribute('data-error-character')).toBe('E')
  const rateOrder = await items.evaluateAll(nodes => nodes.map(node => node.getAttribute('data-error-character')))
  await page.getByRole('combobox', { name: '错误分析排序' }).selectOption('frequent')
  expect(await items.first().getAttribute('data-error-character')).toBe('E')
  const ordered = await items.evaluateAll(nodes => nodes.map(node => node.getAttribute('data-error-character')))
  expect(ordered).not.toEqual(rateOrder)
  await items.last().scrollIntoViewIfNeeded()
  await expect(items.last()).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  const mobile = await boxes()
  expect(mobile[0].x).toBe(mobile[1].x)
  expect(mobile[1].y).toBeGreaterThanOrEqual(mobile[0].y + mobile[0].height)
  expect(await items.evaluateAll(nodes => nodes.map(node => node.getAttribute('data-error-character')))).toEqual(ordered)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await items.last().scrollIntoViewIfNeeded()
  await expect(items.last()).toBeVisible()
})
