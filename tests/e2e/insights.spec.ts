import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
test.use({ timezoneId: 'Asia/Shanghai' })
const route = '/#/practice?themeId=custom-insights&articleId=insight-a'
async function seedTraining(page: Page, language = 'en', autoSave = true) {
  await page.addInitScript(({ language, autoSave }) => {
    if (!localStorage.getItem('typeflow.settings')) localStorage.setItem('typeflow.settings', JSON.stringify({ version: 2, data: { theme: 'light', defaultLanguage: 'zh', defaultMode: 'free', defaultTimedMinutes: 1, correctSound: false, incorrectSound: false, autoSave, dailyGoalMinutes: 20 } }))
    if (!localStorage.getItem('typeflow.library')) {
      const now = new Date().toISOString()
      localStorage.setItem('typeflow.library', JSON.stringify({ version: 1, data: [{ id: 'custom-insights', name: '拓展测试', language, description: '', difficulty: 'beginner', isDefault: false, createdAt: now, updatedAt: now, articles: [{ id: 'insight-a', title: '字符聚合练习', content: language === 'en' ? 'ABCD' : '你好世界', difficulty: 'beginner', createdAt: now, updatedAt: now }] }] }))
    }
  }, { language, autoSave })
  await page.clock.install({ time: new Date('2026-11-04T12:00:00+08:00') })
  await page.goto(route)
  await page.clock.pauseAt(new Date(await page.evaluate(() => Date.now()) + 1000))
}
async function seedHistory(page: Page) {
  await page.addInitScript(() => {
    if (localStorage.getItem('typeflow.history')) return
    const records = [2, 3, 4].map(day => ({ id: `saved-${day}`, themeId: 'deleted-theme', themeName: '原主题', articleId: 'deleted-article', articleTitle: `训练 ${day}`, language: day === 3 ? 'zh' : 'en', mode: 'free', timedMinutes: 1, startedAt: new Date(2026, 10, day, 9).toISOString(), completedAt: new Date(2026, 10, day, 10).toISOString(), finishReason: 'article-completed', metrics: { cpm: 10, wpm: 2, accuracy: 75, cumulativeAccuracy: 75, correctCharacters: 3, incorrectCharacters: 1, submittedCharacters: 4, totalInputCharacters: 4, totalCorrectInputCharacters: 3, elapsedMs: 600000, progress: 1 } }))
    localStorage.setItem('typeflow.history', JSON.stringify({ version: 1, data: records }))
  })
}
test('daily goal setting persists; deleting history updates goal and all habit statistics', async ({ page }) => {
  await seedHistory(page)
  await seedTraining(page)
  await page.goto('/#/')
  await expect(page.getByTestId('daily-goal-time')).toHaveText('10.0 / 20 分钟')
  await expect(page.getByRole('progressbar', { name: '每日目标完成进度' })).toHaveAttribute('value', '50')
  await page.getByRole('link', { name: '修改目标' }).click()
  await page.getByRole('spinbutton', { name: '每日训练目标（分钟）' }).fill('5')
  await page.getByRole('button', { name: '保存目标', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('spinbutton', { name: '每日训练目标（分钟）' })).toHaveValue('5')
  await page.goto('/#/')
  await expect(page.getByText('今日目标已达成')).toBeVisible()
  await page.goto('/#/history')
  const habits = page.getByRole('region', { name: '训练习惯与错误分析' })
  await expect(habits.locator('.habit-grid')).toContainText('当前连续3 天')
  await expect(habits.locator('.habit-grid')).toContainText('最长连续3 天')
  await expect(habits.locator('.habit-grid')).toContainText('本周训练3 天')
  await page.getByText('错误字符分析', { exact: true }).click()
  await page.getByRole('group', { name: '错误分析语言' }).getByRole('button', { name: 'English' }).click()
  await expect(habits).toContainText('2 条旧记录无字符明细')
  await expect(habits).toContainText('暂无字符分析数据')
  await page.getByRole('button', { name: '删除训练 4记录', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(habits.locator('.habit-grid')).toContainText('当前连续2 天')
  await page.goto('/#/')
  await expect(page.getByTestId('daily-goal-time')).toHaveText('0.0 / 5 分钟')
  await page.goto('/#/history')
  await page.getByRole('button', { name: '清空记录', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.locator('.habit-grid')).toContainText('最长连续0 天')
})

test('new English records aggregate retained case-sensitive errors after Backspace without input text', async ({ page }) => {
  await seedTraining(page)
  await page.getByRole('button', { name: '开始训练', exact: true }).click()
  const input = page.getByRole('textbox', { name: '训练输入' })
  await input.pressSequentially('AX')
  await input.press('Backspace')
  await page.clock.fastForward(1000)
  await input.pressSequentially('BYD')
  await expect(page.getByText('成绩已保存到训练记录', { exact: true })).toBeVisible()
  const envelope = await page.evaluate(() => JSON.parse(localStorage.getItem('typeflow.history')!))
  expect(envelope.version).toBe(2)
  expect(envelope.data).toHaveLength(1)
  expect(envelope.data[0].characterAnalysis).toEqual({ version: 1, characters: [{ expected: 'A', attempts: 1, errors: 0 }, { expected: 'B', attempts: 1, errors: 0 }, { expected: 'C', attempts: 1, errors: 1 }, { expected: 'D', attempts: 1, errors: 0 }] })
  expect(JSON.stringify(envelope)).not.toContain('ABYD')
  expect(envelope.data[0].metrics.totalInputCharacters).toBe(5)
  await page.goto('/#/history')
  await page.getByText('错误字符分析', { exact: true }).click()
  await page.getByRole('group', { name: '错误分析语言' }).getByRole('button', { name: 'English' }).click()
  await expect(page.locator('.error-character-list')).toContainText('C1 次错误 / 1 次匹配错误率 100.0%')
  await page.getByRole('combobox', { name: '错误分析排序' }).selectOption('highRate')
  await expect(page.locator('.error-character-list li')).toHaveCount(1)
  await page.getByRole('group', { name: '错误分析语言' }).getByRole('button', { name: '中文', exact: true }).click()
  await expect(page.getByText('暂无字符分析数据，完成新训练后查看')).toBeVisible()
  await page.goto('/#/')
  await expect(page.getByTestId('daily-goal-time')).toHaveText('0.0 / 20 分钟')
  await expect(page.getByRole('progressbar', { name: '每日目标完成进度' })).not.toHaveAttribute('value', '0')
  await page.goto('/#/history')
  await page.getByText('错误字符分析', { exact: true }).click()
  await page.getByRole('group', { name: '错误分析语言' }).getByRole('button', { name: 'English' }).click()
  await page.getByRole('button', { name: '删除字符聚合练习记录', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.locator('.error-character-list')).toHaveCount(0)
  await expect(page.locator('.habit-grid')).toContainText('最长连续0 天')
  await page.goto('/#/')
  await expect(page.getByRole('progressbar', { name: '每日目标完成进度' })).toHaveAttribute('value', '0')
})

test('Chinese candidate commits count once and corrected/deleted characters do not remain errors', async ({ page }) => {
  await seedTraining(page, 'zh')
  await page.getByRole('button', { name: '开始训练', exact: true }).click()
  const input = page.getByRole('textbox', { name: '训练输入' })
  await input.evaluate((node: HTMLTextAreaElement) => {
    node.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true }))
    node.value = 'nihao'
    node.dispatchEvent(new InputEvent('input', { bubbles: true, isComposing: true }))
  })
  expect(await page.evaluate(() => localStorage.getItem('typeflow.history'))).toBeNull()
  await input.evaluate((node: HTMLTextAreaElement) => {
    node.value = '你错'
    node.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true, data: '你错' }))
    node.dispatchEvent(new InputEvent('input', { bubbles: true, data: '你错' }))
  })
  await input.press('Backspace')
  await page.clock.fastForward(1000)
  await input.pressSequentially('好世错')
  await expect(page.getByText('成绩已保存到训练记录', { exact: true })).toBeVisible()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('typeflow.history')!).data[0])
  expect(saved.characterAnalysis.characters).toEqual([{ expected: '你', attempts: 1, errors: 0 }, { expected: '好', attempts: 1, errors: 0 }, { expected: '世', attempts: 1, errors: 0 }, { expected: '界', attempts: 1, errors: 1 }])
  expect(saved.metrics.totalInputCharacters).toBe(5)
  await page.goto('/#/history')
  await page.getByText('错误字符分析', { exact: true }).click()
  await expect(page.locator('.error-character-list')).toContainText('界')
  await expect(page.locator('.error-character-list li')).toHaveCount(1)
})

