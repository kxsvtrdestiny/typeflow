import { test, expect } from '@playwright/test'

test('default library filters, search, readonly detail, and practice handoff', async ({ page }) => {
  await page.goto('/#/library')
  await expect(page.locator('.library-card')).toHaveCount(6)
  await expect(page.getByText('默认 · 只读', { exact: true })).toHaveCount(6)
  await expect(page.locator('.library-card').getByText('5 篇文章')).toHaveCount(6)
  await page.getByRole('button', { name: 'English', exact: true }).click()
  await expect(page.locator('.library-card')).toHaveCount(6)
  await page.getByRole('textbox', { name: '搜索主题' }).fill('DAILY')
  await expect(page.locator('.library-card')).toHaveCount(1)
  await page.getByRole('link', { name: '查看文章' }).click()
  await expect(page.locator('.article-card')).toHaveCount(5)
  await expect(page.getByRole('button', { name: '添加文章' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^编辑/ })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^删除/ })).toHaveCount(0)
  await page.getByRole('link', { name: '开始练习' }).first().click()
  await expect(page.getByRole('heading', { name: '已选练习' })).toBeVisible()
  await expect(page.locator('.practice-selection')).toContainText('A Quiet Morning')
  await page.goto('/#/library')
  await page.getByRole('combobox', { name: '筛选难度' }).selectOption('advanced')
  await expect(page.locator('.library-card')).toHaveCount(2)
})

test('theme and article CRUD, cancellation, refresh persistence', async ({ page }) => {
  await page.goto('/#/library')
  await page.getByRole('button', { name: '新建主题' }).click()
  await page.getByRole('textbox', { name: '主题名称' }).fill('私人练习')
  await page.getByRole('textbox', { name: '主题描述' }).fill('我自己的素材')
  await page.getByRole('button', { name: '保存主题' }).click()
  await expect(page.locator('.library-card')).toHaveCount(7)
  await page.reload()
  await expect(page.locator('.library-card')).toHaveCount(7)
  await page.getByRole('button', { name: '编辑私人练习', exact: true }).click()
  await page.getByRole('textbox', { name: '主题名称' }).fill('改名主题')
  await page.getByRole('combobox', { name: '难度', exact: true }).selectOption('advanced')
  await page.getByRole('button', { name: '保存主题' }).click()
  const card = page.locator('.library-card').filter({ has: page.getByRole('heading', { name: '改名主题' }) })
  await card.getByRole('link', { name: '查看文章' }).click()
  await page.getByRole('button', { name: '添加文章' }).click()
  await page.getByRole('textbox', { name: '文章标题' }).fill('第一篇')
  await page.getByRole('textbox', { name: '文章内容' }).fill('你好，世界。\nThis is a complete practice passage.')
  await page.getByRole('combobox', { name: '文章难度' }).selectOption('intermediate')
  await page.getByRole('button', { name: '保存文章' }).click()
  await page.reload()
  await expect(page.locator('.article-card')).toHaveCount(1)
  await expect(page.locator('.article-card')).toContainText('中等')
  await page.getByRole('button', { name: '编辑第一篇', exact: true }).click()
  await page.getByRole('textbox', { name: '文章标题' }).fill('修订文章')
  await page.getByRole('textbox', { name: '文章内容' }).fill('这是修订后的完整练习。')
  await page.getByRole('button', { name: '保存文章' }).click()
  await page.getByRole('button', { name: '删除修订文章', exact: true }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.article-card')).toHaveCount(1)
  await page.getByRole('button', { name: '删除修订文章', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByRole('heading', { name: '暂无文章' })).toBeVisible()
  await page.getByRole('link', { name: '返回词库', exact: true }).click()
  await page.getByRole('button', { name: '编辑改名主题', exact: true }).click()
  await page.getByRole('combobox', { name: '语言', exact: true }).selectOption('en')
  await page.getByRole('button', { name: '保存主题' }).click()
  await expect(page.getByRole('heading', { name: '改名主题' })).toBeVisible()
  await page.getByRole('button', { name: '删除改名主题', exact: true }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('heading', { name: '改名主题' })).toBeVisible()
  await page.getByRole('button', { name: '删除改名主题', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'English', exact: true }).click()
  await expect(page.locator('.library-card')).toHaveCount(6)
  await page.getByRole('textbox', { name: '搜索主题' }).fill('改名主题')
  await expect(page.getByRole('heading', { name: '暂无匹配主题' })).toBeVisible()
})

test('corrupted storage remains intact and defaults stay usable on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => localStorage.setItem('typeflow.library', '{broken'))
  await page.goto('/#/library')
  await expect(page.getByRole('alert')).toContainText('原始数据已保留')
  await expect(page.getByRole('button', { name: '新建主题' })).toBeDisabled()
  await expect(page.locator('.library-card')).toHaveCount(6)
  expect(await page.evaluate(() => localStorage.getItem('typeflow.library'))).toBe('{broken')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('link', { name: '查看文章' }).first().click()
  await expect(page.locator('.article-card')).toHaveCount(5)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
